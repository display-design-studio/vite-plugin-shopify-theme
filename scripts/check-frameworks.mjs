import { execFileSync, spawn } from 'node:child_process';
import { cpSync, existsSync, mkdtempSync, readFileSync, readdirSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const baseFixture = join(root, 'test', 'fixtures', 'compatibility');
const frameworkFixtures = join(root, 'test', 'fixtures', 'frameworks');
const mode = process.argv[2] ?? 'all';
const frameworks = mode === 'all' ? ['vue', 'react'] : [mode];

if (!['all', 'vue', 'react'].includes(mode)) {
  throw new Error(`Unknown framework compatibility mode ${JSON.stringify(mode)}. Use "vue", "react", or "all".`);
}

const specifications = {
  vue: ['vite@8', '@vitejs/plugin-vue@6', 'vue@3'],
  react: ['vite@8', '@vitejs/plugin-react@6', 'react@19', 'react-dom@19'],
};

function read(path, context) {
  if (!existsSync(path)) throw new Error(`[frameworks: ${context}] expected file is missing: ${path}`);
  return readFileSync(path, 'utf8');
}

function run(command, args, options, context) {
  try {
    execFileSync(command, args, { stdio: 'inherit', ...options });
  } catch (error) {
    throw new Error(`[frameworks: ${context}] command failed: ${command} ${args.join(' ')}`, { cause: error });
  }
}

function packageTarball(directory) {
  const output = execFileSync('npm', ['pack', '--json', '--pack-destination', directory], {
    cwd: root,
    encoding: 'utf8',
    env: { ...process.env, npm_config_cache: join(directory, 'npm-cache') },
  });
  const [result] = JSON.parse(output);
  if (!result?.filename) throw new Error('[frameworks: pack] npm pack did not report a tarball filename.');
  return join(directory, result.filename);
}

async function waitFor(predicate, context, timeout = 30_000) {
  const deadline = Date.now() + timeout;
  let lastError;
  while (Date.now() < deadline) {
    try {
      const result = await predicate();
      if (result) return result;
    } catch (error) {
      lastError = error;
    }
    await new Promise((resolvePromise) => setTimeout(resolvePromise, 100));
  }
  throw new Error(`[frameworks: ${context}] timed out${lastError ? `: ${lastError.message}` : ''}`);
}

async function stop(child, context) {
  if (child.exitCode !== null || child.signalCode !== null) return;
  child.kill('SIGTERM');
  await waitFor(() => child.exitCode !== null || child.signalCode !== null, `${context} shutdown`, 10_000);
}

async function checkFramework(base, framework, tarball) {
  const directory = join(base, framework);
  cpSync(baseFixture, directory, { recursive: true });
  cpSync(join(frameworkFixtures, framework), directory, { recursive: true, force: true });
  const cache = join(base, 'npm-cache');
  run('npm', ['install', '--no-audit', '--no-fund', '--save-exact', tarball, ...specifications[framework]], {
    cwd: directory,
    env: { ...process.env, npm_config_cache: cache },
  }, `${framework} install`);
  if (framework === 'react') {
    const resolvedPreamble = execFileSync(process.execPath, [
      '--input-type=module',
      '--eval',
      "console.log(import.meta.resolve('@vitejs/plugin-react/preamble'))",
    ], { cwd: directory, encoding: 'utf8' }).trim();
    if (!resolvedPreamble.startsWith('file:') || !existsSync(fileURLToPath(resolvedPreamble))) {
      throw new Error('[frameworks: react preamble] the package export did not resolve to an installed module.');
    }
  }

  run('npm', ['exec', '--', 'vite', 'build'], { cwd: directory }, `${framework} production build`);
  const manifest = JSON.parse(read(join(directory, 'assets', 'vite-manifest.json'), `${framework} manifest`));
  const extension = framework === 'vue' ? 'js' : 'jsx';
  const source = `frontend/entrypoints/section.${extension}`;
  const output = manifest[source]?.file;
  if (!output) throw new Error(`[frameworks: ${framework} manifest] entry ${JSON.stringify(source)} is missing.`);
  read(join(directory, 'assets', output), `${framework} production entry`);
  const snippetPath = join(directory, 'snippets', 'vite-tag.liquid');
  const productionSnippet = read(snippetPath, `${framework} production snippet`);
  if (!productionSnippet.includes(`{% when 'section.${extension}' %}`) || !productionSnippet.includes('Generated by vite-plugin-shopify-theme')) {
    throw new Error(`[frameworks: ${framework} snippet] generated entry branch or marker is missing.`);
  }
  if (!readdirSync(join(directory, 'assets')).some((name) => name.endsWith('.js'))) {
    throw new Error(`[frameworks: ${framework} output] no JavaScript bundle was emitted.`);
  }

  const child = spawn(process.execPath, [join(directory, 'node_modules', 'vite', 'bin', 'vite.js'), '--host', '127.0.0.1', '--port', '0'], {
    cwd: directory,
    env: process.env,
    stdio: ['ignore', 'pipe', 'pipe'],
  });
  let logs = '';
  child.stdout.on('data', (chunk) => { logs += chunk; });
  child.stderr.on('data', (chunk) => { logs += chunk; });

  try {
    const developmentSnippet = await waitFor(() => {
      if (child.exitCode !== null || child.signalCode !== null) {
        throw new Error(`dev server exited with ${child.exitCode ?? child.signalCode}\n${logs}`);
      }
      const content = readFileSync(snippetPath, 'utf8');
      return content.includes('Temporary development file') ? content : undefined;
    }, `${framework} development snippet`);
    const origin = developmentSnippet.match(/(http:\/\/127\.0\.0\.1:\d+)\/@vite\/client/)?.[1];
    if (!origin) throw new Error(`[frameworks: ${framework} dev server] could not find the listening origin in the generated snippet.`);

    const entryUrl = `${origin}/${source}`;
    const entryResponse = await waitFor(async () => {
      const response = await fetch(entryUrl);
      return response.ok ? response : undefined;
    }, `${framework} development entry`);
    const transformed = await entryResponse.text();
    const expectedModules = framework === 'vue' ? ['vue', 'SectionApp.vue'] : ['react', 'react-dom'];
    for (const expected of expectedModules) {
      if (!transformed.includes(expected)) throw new Error(`[frameworks: ${framework} dev entry] transformed module does not reference ${expected}.`);
    }

    const modulePaths = [...transformed.matchAll(/(?:from\s*|import\s*)["']([^"']+)["']/g)].map((match) => match[1]);
    const frameworkModule = modulePaths.find((path) => path.includes(framework));
    if (!frameworkModule) throw new Error(`[frameworks: ${framework} dev entry] no framework module URL was generated.`);
    const moduleResponse = await fetch(new URL(frameworkModule, entryUrl));
    if (!moduleResponse.ok) throw new Error(`[frameworks: ${framework} dev module] ${frameworkModule} returned ${moduleResponse.status}.`);

  } finally {
    await stop(child, framework);
  }

  const restored = read(snippetPath, `${framework} restored snippet`);
  if (restored !== productionSnippet) throw new Error(`[frameworks: ${framework} shutdown] the production snippet was not restored exactly.`);
  console.log(`[frameworks] ${framework} passed on Node ${process.version}.`);
}

const temporary = mkdtempSync(join(tmpdir(), 'vite-plugin-shopify-theme-frameworks-'));
try {
  const tarball = packageTarball(temporary);
  for (const framework of frameworks) await checkFramework(temporary, framework, tarball);
} catch (error) {
  console.error(error instanceof Error ? error.stack : error);
  process.exitCode = 1;
} finally {
  rmSync(temporary, { recursive: true, force: true });
}
