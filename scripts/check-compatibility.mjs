import { execFileSync } from 'node:child_process';
import { cpSync, existsSync, mkdtempSync, readFileSync, readdirSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execNpmSync } from './npm-command.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const fixture = join(root, 'test', 'fixtures', 'compatibility');
const mode = process.argv[2] ?? 'all';
const viteVersion = process.env.VITE_VERSION || '8';
const shopifyVersion = process.env.SHOPIFY_CLI_VERSION || '4';
const allowedModes = new Set(['vite', 'shopify', 'all']);

if (!allowedModes.has(mode)) {
  throw new Error(`Unknown compatibility mode ${JSON.stringify(mode)}. Use "vite", "shopify", or "all".`);
}

function run(command, args, options, context) {
  try {
    const executionOptions = { stdio: 'inherit', ...options };
    if (command === 'npm') execNpmSync(args, executionOptions);
    else execFileSync(command, args, executionOptions);
  } catch (error) {
    throw new Error(`[compatibility: ${context}] command failed: ${command} ${args.join(' ')}`, { cause: error });
  }
}

function read(path, context) {
  if (!existsSync(path)) throw new Error(`[compatibility: ${context}] expected output is missing: ${path}`);
  return readFileSync(path, 'utf8');
}

function packageTarball(directory) {
  const output = execNpmSync(['pack', '--json', '--pack-destination', directory], {
    cwd: root,
    encoding: 'utf8',
    env: { ...process.env, npm_config_cache: join(directory, 'npm-cache') },
  });
  const parsed = JSON.parse(output);
  const result = Array.isArray(parsed)
    ? parsed[0]
    : parsed?.filename
      ? parsed
      : Object.values(parsed ?? {})[0];
  if (!result?.filename) throw new Error('[compatibility: pack] npm pack did not report a tarball filename.');
  return join(directory, result.filename);
}

function install(directory, specifications, context) {
  run('npm', ['install', '--no-audit', '--no-fund', '--save-exact', ...specifications], {
    cwd: directory,
    env: { ...process.env, npm_config_cache: join(directory, 'npm-cache') },
  }, context);
}

function checkVite(base) {
  const directory = join(base, `vite-${viteVersion.replaceAll('/', '-')}`);
  cpSync(fixture, directory, { recursive: true });
  const tarball = packageTarball(base);
  install(directory, [tarball, `vite@${viteVersion}`], `Vite ${viteVersion} install`);
  run('npm', ['exec', '--', 'vite', 'build'], { cwd: directory }, `Vite ${viteVersion} build`);

  const assets = join(directory, 'assets');
  const manifestPath = join(assets, 'vite-manifest.json');
  const manifest = JSON.parse(read(manifestPath, `Vite ${viteVersion} manifest`));
  const expectedEntries = ['frontend/entrypoints/theme.css', 'frontend/entrypoints/theme.ts'];
  for (const entry of expectedEntries) {
    const output = manifest[entry]?.file;
    if (!output) throw new Error(`[compatibility: Vite ${viteVersion} manifest] entry ${JSON.stringify(entry)} is missing.`);
    read(join(assets, output), `Vite ${viteVersion} asset for ${entry}`);
  }

  const snippet = read(join(directory, 'snippets', 'vite-tag.liquid'), `Vite ${viteVersion} generated snippet`);
  for (const entry of ['theme.css', 'theme.ts']) {
    if (!snippet.includes(`{% when '${entry}' %}`)) throw new Error(`[compatibility: Vite ${viteVersion} snippet] entry ${JSON.stringify(entry)} is missing.`);
  }
  if (!snippet.includes('Generated by vite-plugin-shopify-theme')) throw new Error(`[compatibility: Vite ${viteVersion} snippet] generated marker is missing.`);
  read(join(assets, 'manual.txt'), `Vite ${viteVersion} preserved manual asset`);
  read(join(directory, 'snippets', 'manual.liquid'), `Vite ${viteVersion} preserved manual snippet`);
  const generated = readdirSync(assets).filter((name) => /-[A-Za-z0-9_-]{8,}\.(?:css|js)$/.test(name));
  if (generated.length < 2) throw new Error(`[compatibility: Vite ${viteVersion} output] expected CSS and JavaScript assets, found: ${generated.join(', ') || '(none)'}.`);
  console.log(`[compatibility] Vite ${viteVersion} passed on Node ${process.version}.`);
}

function checkShopify(base) {
  const directory = join(base, `shopify-${shopifyVersion.replaceAll('/', '-')}`);
  cpSync(fixture, directory, { recursive: true });
  install(directory, [`@shopify/cli@${shopifyVersion}`], `Shopify CLI ${shopifyVersion} install`);
  run('npm', ['exec', '--', 'shopify', 'theme', 'check', '--path', directory], { cwd: directory }, `Shopify CLI ${shopifyVersion} Theme Check`);
  console.log(`[compatibility] Shopify CLI ${shopifyVersion} Theme Check passed on Node ${process.version}.`);
}

const temporary = mkdtempSync(join(tmpdir(), 'vite-plugin-shopify-theme-compatibility-'));
try {
  if (mode === 'vite' || mode === 'all') checkVite(temporary);
  if (mode === 'shopify' || mode === 'all') checkShopify(temporary);
} catch (error) {
  console.error(error instanceof Error ? error.stack : error);
  process.exitCode = 1;
} finally {
  rmSync(temporary, { recursive: true, force: true });
}
